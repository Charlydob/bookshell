const API_BASE = String(API_BASE_URL || "").replace(/\/+$/g, "");
const POLL_INTERVAL_MS = 15000;
const HIDDEN_POLL_INTERVAL_MS = 30000;
const PUSH_CHARS = "-0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ_abcdefghijklmnopqrstuvwxyz";
