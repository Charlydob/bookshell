function normalizePatchKeys(basePath = "", patch = {}) {
  if (!isPlainObject(patch)) return patch || {};
  return Object.fromEntries(
    Object.entries(patch).map(([key, value]) => {
      const fullPath = basePath ? joinPath(basePath, key) : key;
      const normalizedFullPath = normalizeDataPath(fullPath);
      const relative = basePath && normalizedFullPath.startsWith(`${basePath}/`)
        ? normalizedFullPath.slice(basePath.length + 1)
        : normalizedFullPath;
      return [basePath ? relative : normalizedFullPath, value];
    }),
  );
}

export async function patchValue(pathOrRef, patch = {}) {
  const target = resolveTarget(pathOrRef);
  const basePath = normalizeDataPath(target);
  const normalizedPatch = normalizePatchKeys(basePath, patch || {});
  logUsage("UPDATE", target);
  await requestJson("PATCH", basePath, { body: normalizedPatch, debugMethod: "PATCH" });
}

