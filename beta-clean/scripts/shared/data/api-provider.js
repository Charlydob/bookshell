function trimSlashes(value = "") {
  return String(value || "").trim().replace(/^\/+|\/+$/g, "");
}

function splitPath(path = "") {
  return trimSlashes(path)
    .split("/")
    .map((part) => part.trim())
    .filter(Boolean);
}

function joinPath(...parts) {
  return parts.map(trimSlashes).filter(Boolean).join("/");
}

function isPlainObject(value) {
  return !!value && typeof value === "object" && !Array.isArray(value);
}

function cloneValue(value) {
  if (value === undefined) return undefined;
  if (value == null) return value;
  try {
    return JSON.parse(JSON.stringify(value));
  } catch (_) {
    return value;
  }
}

function stableStringify(value) {
  if (!isPlainObject(value) && !Array.isArray(value)) return JSON.stringify(value);
  const seen = new WeakSet();
  const normalize = (entry) => {
    if (!entry || typeof entry !== "object") return entry;
    if (seen.has(entry)) return "[Circular]";
    seen.add(entry);
    if (Array.isArray(entry)) return entry.map(normalize);
    return Object.fromEntries(Object.keys(entry).sort().map((key) => [key, normalize(entry[key])]));
  };
  return JSON.stringify(normalize(value));
}

function extractPathFromUrl(value = "") {
  const safe = String(value || "").trim();
  if (!safe) return "";
  try {
    const url = new URL(safe);
    return trimSlashes(decodeURIComponent(url.pathname || "").replace(/\.json$/i, ""));
  } catch (_) {
    return trimSlashes(safe.split("?")[0]);
  }
}

export function normalizeDataPath(pathOrRef = "") {
  let rawPath = "";
  if (typeof pathOrRef === "string") {
    rawPath = pathOrRef;
  } else if (pathOrRef && typeof pathOrRef === "object") {
    rawPath = pathOrRef.path || pathOrRef.fullPath || pathOrRef._path || "";
    if (!rawPath && pathOrRef.provider !== "api" && typeof pathOrRef.toString === "function") {
      rawPath = extractPathFromUrl(pathOrRef.toString());
    }
  }

  const segments = splitPath(rawPath);
  if (segments[0] === "data") segments.shift();

  // The API stores the authenticated user's JSON tree without v2/users/{uid}.
  // Keep accepting legacy Firebase-style paths generated by existing modules.
  if (segments[0] === "v2" && segments[1] === "users" && segments[2]) {
    return segments.slice(3).join("/");
  }

  return segments.join("/");
}

function getKeyFromPath(path = "") {
  const parts = splitPath(path);
  return parts.length ? parts[parts.length - 1] : null;
}

function buildUrl(endpoint = "", path = "") {
  if (!API_BASE) throw new Error("[api-data] API base URL missing");
  const safeEndpoint = String(endpoint || "").replace(/^\/+|\/+$/g, "");
  const safePath = normalizeDataPath(path);
  const encodedPath = safePath
    .split("/")
    .filter(Boolean)
    .map((part) => encodeURIComponent(part))
    .join("/");
  return `${API_BASE}/${safeEndpoint}${encodedPath ? `/${encodedPath}` : ""}`;
}

function unwrapApiValue(payload) {
  if (!payload || typeof payload !== "object" || Array.isArray(payload)) return payload;
  const keys = Object.keys(payload);
  if (keys.length === 1 && Object.prototype.hasOwnProperty.call(payload, "data")) return payload.data;
  if (keys.length === 1 && Object.prototype.hasOwnProperty.call(payload, "value")) return payload.value;
  if (Object.prototype.hasOwnProperty.call(payload, "ok") && Object.prototype.hasOwnProperty.call(payload, "data")) return payload.data;
  if (Object.prototype.hasOwnProperty.call(payload, "result") && Object.prototype.hasOwnProperty.call(payload, "data")) return payload.data;
  return payload;
}

function extractPushKey(payload) {
  const source = payload && typeof payload === "object" ? payload : {};
  return String(
    source.key
      || source.id
      || source.name
      || source.pathKey
      || source.data?.key
      || source.data?.id
      || source.result?.key
      || "",
  ).trim();
}

function unwrapConflictValue(payload) {
  if (!payload || typeof payload !== "object") return undefined;
  if (Object.prototype.hasOwnProperty.call(payload, "latestValue")) return payload.latestValue;
  if (Object.prototype.hasOwnProperty.call(payload, "currentValue")) return payload.currentValue;
  if (Object.prototype.hasOwnProperty.call(payload, "latest")) return payload.latest;
  if (Object.prototype.hasOwnProperty.call(payload, "current")) return payload.current;
  return unwrapApiValue(payload);
}

async function parseResponse(response) {
  const text = await response.text();
  if (!text) return null;
  try {
    return JSON.parse(text);
  } catch (_) {
    return { message: text };
  }
}

async function requestJson(method, path = "", { body, endpoint = "data", debugMethod = method } = {}) {
  const safePath = normalizeDataPath(path);
  console.debug(`[api-data] ${debugMethod} ${safePath || "/"}`);
  const response = await fetch(buildUrl(endpoint, safePath), {
    method,
    credentials: "include",
    headers: {
      Accept: "application/json",
      ...(body !== undefined ? { "Content-Type": "application/json" } : {}),
    },
    ...(body !== undefined ? { body: JSON.stringify(body) } : {}),
  });
  const payload = await parseResponse(response);
  if (!response.ok) {
    const message = payload?.message || payload?.error || `Bookshell API ${response.status}`;
    const error = new Error(message);
    error.status = response.status;
    error.payload = payload;
    error.path = safePath;
    throw error;
  }
  return payload;
}

function logUsage(operation = "", pathOrRef = "") {
  const path = normalizeDataPath(pathOrRef);
  if (!path) return;
  logDataUsage({ userId: "", path, operation });
}

function createSnapshot(value, pathOrRef = "") {
  const normalizedPath = normalizeDataPath(pathOrRef);
  const snapshotRef = ref(db, normalizedPath);
  const safeValue = cloneValue(value);
  return {
    key: getKeyFromPath(normalizedPath),
    ref: snapshotRef,
    val() {
      return cloneValue(safeValue);
    },
    exists() {
      return safeValue !== null && safeValue !== undefined;
    },
    child(childPath = "") {
      const segments = splitPath(childPath);
      let cursor = safeValue;
      for (const segment of segments) {
        if (!cursor || typeof cursor !== "object") {
          cursor = undefined;
          break;
        }
        cursor = cursor[segment];
      }
      return createSnapshot(cursor, joinPath(normalizedPath, childPath));
    },
    forEach(callback) {
      if (!isPlainObject(safeValue) || typeof callback !== "function") return false;
      for (const [key, entry] of Object.entries(safeValue)) {
        const shouldCancel = callback(createSnapshot(entry, joinPath(normalizedPath, key)));
        if (shouldCancel === true) return true;
      }
      return false;
    },
    numChildren() {
      if (!isPlainObject(safeValue) && !Array.isArray(safeValue)) return 0;
      return Object.keys(safeValue).length;
    },
    toJSON() {
      return cloneValue(safeValue);
    },
  };
}

function resolveTarget(pathOrQuery = "") {
  if (pathOrQuery && typeof pathOrQuery === "object" && pathOrQuery.__apiQuery) return pathOrQuery;
  if (pathOrQuery && typeof pathOrQuery === "object" && pathOrQuery.path != null) return pathOrQuery;
  return ref(db, String(pathOrQuery || ""));
}

function applyQuery(value, querySpec = null) {
  if (!querySpec?.__apiQuery || !isPlainObject(value)) return value;
  const constraints = querySpec.constraints || {};
  const orderChild = constraints.orderByChild || "";
  let rows = Object.entries(value).map(([key, entry]) => ({ key, value: entry }));
  if (orderChild) {
    rows.sort((left, right) => {
      const a = left.value?.[orderChild];
      const b = right.value?.[orderChild];
      if (a == null && b == null) return left.key.localeCompare(right.key);
      if (a == null) return -1;
      if (b == null) return 1;
      if (a < b) return -1;
      if (a > b) return 1;
      return left.key.localeCompare(right.key);
    });
  }
  if (Object.prototype.hasOwnProperty.call(constraints, "startAt")) {
    rows = rows.filter((row) => {
      const valueToCompare = orderChild ? row.value?.[orderChild] : row.key;
      return valueToCompare >= constraints.startAt;
    });
  }
  if (Object.prototype.hasOwnProperty.call(constraints, "endAt")) {
    rows = rows.filter((row) => {
      const valueToCompare = orderChild ? row.value?.[orderChild] : row.key;
      return valueToCompare <= constraints.endAt;
    });
  }
  if (Number.isFinite(Number(constraints.limitToFirst))) {
    rows = rows.slice(0, Math.max(0, Math.floor(Number(constraints.limitToFirst))));
  }
  return Object.fromEntries(rows.map((row) => [row.key, row.value]));
}

function makePushId(now = Date.now()) {
  const duplicateTime = now === lastPushTime;
  lastPushTime = now;
  const timeStampChars = new Array(8);
  for (let i = 7; i >= 0; i -= 1) {
    timeStampChars[i] = PUSH_CHARS.charAt(now % 64);
    now = Math.floor(now / 64);
  }
  if (!duplicateTime) {
    lastRandChars = Array.from({ length: 12 }, () => Math.floor(Math.random() * 64));
  } else {
    for (let i = 11; i >= 0; i -= 1) {
      if (lastRandChars[i] !== 63) {
        lastRandChars[i] += 1;
        break;
      }
      lastRandChars[i] = 0;
    }
  }
  return `${timeStampChars.join("")}${lastRandChars.map((index) => PUSH_CHARS.charAt(index)).join("")}`;
}

export function ref(dbOrPath = "", maybePath = undefined) {
  const rawPath = maybePath === undefined && dbOrPath?.provider === "api" ? "" : (maybePath === undefined ? dbOrPath : maybePath);
  const path = normalizeDataPath(rawPath || "");
  const target = {
    provider: "api",
    path,
    fullPath: path,
    key: getKeyFromPath(path),
    get parent() {
      const parts = splitPath(path);
      return parts.length > 1 ? ref(db, parts.slice(0, -1).join("/")) : null;
    },
    get root() {
      return ref(db, "");
    },
    toString() {
      return path;
    },
  };
  target.ref = target;
  return target;
}

export async function readOnce(pathOrQuery) {
  const target = resolveTarget(pathOrQuery);
  if (normalizeDataPath(target) === ".info/connected") {
    return createSnapshot(typeof navigator === "undefined" ? true : navigator.onLine !== false, ".info/connected");
  }
  logUsage("READ", target);
  const payload = await requestJson("GET", target.path || target, { debugMethod: "GET" });
  const value = applyQuery(unwrapApiValue(payload), target);
  return createSnapshot(value ?? null, target.path || target);
}

export async function readValue(pathOrQuery) {
  const snap = await readOnce(pathOrQuery);
  return snap.val();
}

