export function onValue(pathOrQuery, callback, onError) {
  const target = resolveTarget(pathOrQuery);
  const path = target.path || normalizeDataPath(target);

  if (path === ".info/connected") {
    let active = true;
    const emit = () => {
      if (!active) return;
      callback?.(createSnapshot(typeof navigator === "undefined" ? true : navigator.onLine !== false, path));
    };
    window.addEventListener?.("online", emit);
    window.addEventListener?.("offline", emit);
    queueMicrotask(emit);
    return () => {
      active = false;
      window.removeEventListener?.("online", emit);
      window.removeEventListener?.("offline", emit);
    };
  }

  logUsage("LISTEN", target);
  let active = true;
  let timer = 0;
  let inFlight = false;
  let lastSerialized = "";

  // Temporary API listener: polling until the backend exposes SSE/WebSocket.
  const poll = async () => {
    if (!active || inFlight) return;
    inFlight = true;
    try {
      const snap = await readOnce(target);
      const serialized = stableStringify(snap.val());
      if (serialized !== lastSerialized) {
        lastSerialized = serialized;
        callback?.(snap);
      }
    } catch (error) {
      onError?.(error);
    } finally {
      inFlight = false;
      if (active) {
        const hidden = typeof document !== "undefined" && document.visibilityState === "hidden";
        timer = window.setTimeout(poll, hidden ? HIDDEN_POLL_INTERVAL_MS : POLL_INTERVAL_MS);
      }
    }
  };

  void poll();

  return () => {
    active = false;
    if (timer) window.clearTimeout(timer);
  };
}

